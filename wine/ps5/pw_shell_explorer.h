/* ---------- locations ---------- */
static ITEMIDLIST *pw_explorer_pidl(int location)
{
    static const int folders[PW_LOCATIONS] = {-1, CSIDL_MYPICTURES, CSIDL_DESKTOPDIRECTORY, -2, CSIDL_PERSONAL,
                                              CSIDL_MYPICTURES, CSIDL_MYMUSIC, CSIDL_MYVIDEO, CSIDL_DRIVES, CSIDL_NETWORK,
                                              CSIDL_BITBUCKET, -1, -1};
    ITEMIDLIST *pidl = NULL;
    if (location < 0 || location >= PW_LOCATIONS || folders[location] == -1) return NULL;
    if (folders[location] == -2) SHGetKnownFolderIDList(&FOLDERID_Downloads, 0, NULL, &pidl);
    else SHGetSpecialFolderLocation(NULL, folders[location], &pidl);
    return pidl;
}
static int pw_explorer_location_of(const ITEMIDLIST *pidl)
{
    WCHAR path[MAX_PATH], known_path[MAX_PATH];
    BOOL filesystem = pidl && SHGetPathFromIDListW(pidl, path);
    int i;
    /* Gallery browses Pictures, so a Pictures pidl names Pictures. A folder of the file system is matched by its path:
     * a parsed path's pidl and the known folder's do not compare equal item by item. */
    for (i = PW_LOC_DESKTOP; i <= PW_LOC_RECYCLE; ++i)
    {
        ITEMIDLIST *known = pw_explorer_pidl(i);
        BOOL same = known && pidl && (filesystem ? SHGetPathFromIDListW(known, known_path) && !lstrcmpiW(known_path, path)
                                                 : ILIsEqual(known, pidl));
        CoTaskMemFree(known);
        if (same) return i;
    }
    if (filesystem && PathIsRootW(path)) return PW_LOC_DRIVE;
    return PW_LOC_FOLDER;
}
static IShellView *pw_explorer_view(explorer_info *info)
{
    IShellView *view = NULL;
    if (FAILED(IExplorerBrowser_GetCurrentView(info->browser, &IID_IShellView, (void **)&view))) return NULL;
    return view;
}
static HWND pw_explorer_list(explorer_info *info)
{
    IShellView *view = pw_explorer_view(info); HWND window = NULL;
    if (view) { IShellView_GetWindow(view, &window); IShellView_Release(view); }
    return window ? FindWindowExW(window, NULL, WC_LISTVIEWW, NULL) : NULL;
}

/* The prototype's Filter command shows in folders, not on Home, This PC, Gallery or Network. */
static int pw_explorer_filter(const struct pw_explorer *ui)
{
    return !ui->home && ui->location != PW_LOC_THISPC && ui->location != PW_LOC_NETWORK && ui->location != PW_LOC_GALLERY;
}

/* ---------- the window's elements ---------- */
static PwExplorerBox pw_explorer_element(const struct pw_explorer *ui, int element)
{
    const PwExplorerPlace *p = &ui->place;
    if (element >= PX_TABS) return (element - PX_TABS) & 1 ? ui->tab_close[(element - PX_TABS) / 2] : ui->tab_box[(element - PX_TABS) / 2];
    switch (element)
    {
    case PX_TAB_ADD: return ui->tab_add;
    case PX_MIN: case PX_MAX: case PX_CLOSE: return p->caption[element - PX_MIN];
    case PX_BACK: case PX_FORWARD: case PX_UP: case PX_REFRESH: return p->navigation[element - PX_BACK];
    case PX_ADDRESS: return p->address;
    case PX_SEARCH: return p->search;
    case PX_STATUS_DETAILS: return p->status_details;
    case PX_STATUS_LARGE: return p->status_large;
    default: return p->command[element - PX_COMMAND];
    }
}
static RECT pw_explorer_element_rect(const struct pw_explorer *ui, int element)
{
    PwExplorerBox b = pw_explorer_element(ui, element);
    RECT r = {(int)floor(b.x), (int)floor(b.y), (int)ceil(b.x + b.w), (int)ceil(b.y + b.h)};
    return r;
}
static int pw_explorer_element_at(const struct pw_explorer *ui, POINT pt)
{
    int i;
    for (i = 0; i < PX_TABS + 2 * ui->tabs; ++i)
    {
        /* Each tab's close button before its tab (it is there even when it is not drawn, as the prototype's); the
         * strip clips tabs past its end. */
        int element = i < PX_TABS ? i : PX_TABS + ((i - PX_TABS) ^ 1);
        PwExplorerBox b = pw_explorer_element(ui, element);
        if (element >= PX_TABS && pt.x >= ui->tab_add.x + 4) continue;
        if (pt.x >= b.x && pt.x < b.x + b.w && pt.y >= b.y && pt.y < b.y + b.h) return element;
    }
    return PX_NONE;
}
static void pw_explorer_invalidate(HWND hwnd, const struct pw_explorer *ui, int element)
{
    RECT r;
    if (element == PX_NONE) return;
    /* A tab's state shows on its neighbours' separators too. */
    if (element >= PX_TABS) { SetRect(&r, 0, 0, ui->width, PW_EXPLORER_TITLE_H); InvalidateRect(hwnd, &r, FALSE); return; }
    r = pw_explorer_element_rect(ui, element);
    InflateRect(&r, 1, 1);
    InvalidateRect(hwnd, &r, FALSE);
}

/* ---------- painting the window ---------- */
/* A tab sprite (captured on a 240 px tab) at a tab of any width: its left and right parts as captured, the column
 * after the left part stretched between them. */
static void pw_explorer_sprite_tab(struct pw_explorer *ui, HDC dc, BOOL dark, int id, PwExplorerBox box, int left, int right)
{
    const struct pw_explorer_sprite *s = &pw_explorer_sprites[!!dark][id];
    int x = (int)floor(box.x + 1e-6) + s->dx, y = (int)floor(box.y + 1e-6) + s->dy;
    int w = s->width - 240 + (int)floor(box.x + box.w + 1e-6) - (int)floor(box.x + 1e-6);
    if (w == s->width) { pw_explorer_sprite_part(ui, dc, dark, id, 0, 0, s->width, s->height, x, y, w, s->height); return; }
    pw_explorer_sprite_part(ui, dc, dark, id, 0, 0, left, s->height, x, y, left, s->height);
    pw_explorer_sprite_part(ui, dc, dark, id, left, 0, 1, s->height, x + left, y, w - left - right, s->height);
    pw_explorer_sprite_part(ui, dc, dark, id, s->width - right, 0, right, s->height, x + w - right, y, right, s->height);
}
/* Tab i: the selected one on the header's colour with its outward corners, the others bare (a plate under the pointer,
 * a separator before an unselected neighbour); the location's icon, its name (the selected and hot tabs' in
 * TextFillColorPrimary, the others' Secondary), the close button on the selected and hot tabs. */
static void pw_explorer_paint_tab(explorer_info *info, HDC dc, int i)
{
    struct pw_explorer *ui = info->ui; BOOL dark = info->mihawk_style.dark, selected = i == ui->current;
    PwExplorerBox box = ui->tab_box[i];
    BOOL hot = ui->hot == PX_TABS + 2 * i || ui->hot == PX_TABS + 2 * i + 1;
    BOOL next_hot = ui->hot == PX_TABS + 2 * (i + 1) || ui->hot == PX_TABS + 2 * (i + 1) + 1;
    int location = selected ? ui->location : ui->tab[i].location, shift = (int)floor(box.x + 1e-6) - 8;
    const WCHAR *name = selected ? ui->name : ui->tab[i].name;
    if (selected && location == PW_LOC_HOME && box.w == 240) pw_explorer_sprite(ui, dc, dark, PW_XS_TAB_HOME, box, 0, 0);
    else
    {
        const struct pw_explorer_sprite *icon = &pw_explorer_sprites[!!dark][pw_explorer_tab_icons[location]];
        RECT title = {shift + 43, 20, (int)floor(box.x + box.w + 1e-6) - 41, 37};
        if (selected) pw_explorer_sprite_tab(ui, dc, dark, PW_XS_TAB, box, 20, 52);
        else if (hot) pw_explorer_sprite_tab(ui, dc, dark, PW_XS_TAB_UNSELECTED_HOVER, box, 10, 44);
        else if (i + 1 < ui->tabs && i + 1 != ui->current && !next_hot)
        {
            const struct pw_explorer_sprite *line = &pw_explorer_sprites[!!dark][PW_XS_TAB_UNSELECTED];
            pw_explorer_sprite_part(ui, dc, dark, PW_XS_TAB_UNSELECTED, line->width - 1, 0, 1, line->height,
                                    (int)floor(box.x + box.w + 1e-6), (int)box.y + line->dy, 1, line->height);
        }
        pw_explorer_sprite_part(ui, dc, dark, pw_explorer_tab_icons[location], 0, 0, icon->width, icon->height,
                                icon->x + shift, icon->y, icon->width, icon->height);
        /* The selected tab's name is on its plate; the others' on the glass, where GDI's text would have no alpha. */
        if (title.right > title.left && selected)
            pw_explorer_text_at(dc, info->mihawk_style.font, name, &title, pw_explorer_text(dark, FALSE), DT_LEFT | DT_VCENTER | DT_END_ELLIPSIS);
        else if (title.right > title.left)
        {
            HGDIOBJ prior = SelectObject(dc, info->mihawk_style.font);
            pw_shell_glass_text(ui->theme, NULL, dc, name, &title, pw_explorer_text(dark, !hot),
                                DT_LEFT | DT_VCENTER | DT_END_ELLIPSIS | DT_SINGLELINE | DT_NOPREFIX);
            SelectObject(dc, prior);
        }
    }
    if (ui->hot == PX_TABS + 2 * i + 1)
        pw_explorer_sprite(ui, dc, dark, ui->pressed == ui->hot ? PW_XS_TAB_CLOSE_PRESS : PW_XS_TAB_CLOSE_HOVER, ui->tab_close[i], 0, 0);
}
static void pw_explorer_paint_title(explorer_info *info, HDC dc)
{
    struct pw_explorer *ui = info->ui; const PwExplorerPlace *p = &ui->place;
    BOOL dark = info->mihawk_style.dark, maximized = IsZoomed(info->main_window);
    int i;
    int saved = SaveDC(dc);
    /* The strip clips at its end; unselected tabs first, the selected one's outward corners go over its neighbours. */
    IntersectClipRect(dc, 0, 0, (int)ui->tab_add.x + 4, PW_EXPLORER_TITLE_H);
    for (i = 0; i < ui->tabs; ++i) if (i != ui->current) pw_explorer_paint_tab(info, dc, i);
    pw_explorer_paint_tab(info, dc, ui->current);
    RestoreDC(dc, saved);
    pw_explorer_sprite(ui, dc, dark, !ui->active ? PW_XS_TAB_ADD_INACTIVE : ui->hot != PX_TAB_ADD ? PW_XS_TAB_ADD :
                       ui->pressed == PX_TAB_ADD ? PW_XS_TAB_ADD_PRESS : PW_XS_TAB_ADD_HOVER, ui->tab_add, 0, 0);
    for (i = 0; i < PW_EXPLORER_CAPTIONS; ++i)
    {
        static const short rest[] = {PW_XS_CAP_MIN, PW_XS_CAP_MAX, PW_XS_CAP_CLOSE}, hover[] = {PW_XS_CAP_MIN_HOVER,
            PW_XS_CAP_MAX_HOVER, PW_XS_CAP_CLOSE_HOVER}, press[] = {PW_XS_CAP_MIN_PRESS, PW_XS_CAP_MAX_PRESS,
            PW_XS_CAP_CLOSE_PRESS}, inactive[] = {PW_XS_CAP_MIN_INACTIVE, PW_XS_CAP_MAX_INACTIVE, PW_XS_CAP_CLOSE_INACTIVE};
        int sprite = ui->hot == PX_MIN + i ? (ui->pressed == PX_MIN + i ? press[i] : hover[i]) : ui->active ? rest[i] : inactive[i];
        if (i == 1 && maximized)
            sprite = ui->hot == PX_MAX ? (ui->pressed == PX_MAX ? PW_XS_CAP_RESTORE_PRESS : PW_XS_CAP_RESTORE_HOVER) : PW_XS_CAP_RESTORE;
        pw_explorer_sprite(ui, dc, dark, sprite, p->caption[i], 0, 0);
    }
}

/* The address box's crumbs: the location's icon and the chevron, then each folder from the top of the namespace. */
static void pw_explorer_paint_crumbs(explorer_info *info, HDC dc)
{
    struct pw_explorer *ui = info->ui; const PwExplorerPlace *p = &ui->place;
    BOOL dark = info->mihawk_style.dark;
    RECT clip = {(int)p->address.x + 1, (int)p->address.y + 1, (int)(p->address.x + p->address.w) - 1, (int)(p->address.y + p->address.h) - 1};
    const struct pw_explorer_sprite *icon = &pw_explorer_sprites[!!dark][pw_explorer_crumb_icons[ui->location]];
    const struct pw_explorer_sprite *chevron = &pw_explorer_sprites[!!dark][PW_XS_CRUMB_CHEV];
    int x = 205, saved = SaveDC(dc);
    IntersectClipRect(dc, clip.left, clip.top, clip.right, clip.bottom);
    pw_explorer_sprite_part(ui, dc, dark, pw_explorer_crumb_icons[ui->location], 0, 0, icon->width, icon->height, icon->x, icon->y, icon->width, icon->height);
    pw_explorer_sprite_part(ui, dc, dark, PW_XS_CRUMB_CHEV, 0, 0, chevron->width, chevron->height, chevron->x, chevron->y, chevron->width, chevron->height);
    if (ui->home) pw_explorer_sprite_part(ui, dc, dark, PW_XS_CRUMB_HOME, 0, 0, pw_explorer_sprite_width(dark, PW_XS_CRUMB_HOME),
                                          pw_explorer_sprites[!!dark][PW_XS_CRUMB_HOME].height, 205, 60,
                                          pw_explorer_sprite_width(dark, PW_XS_CRUMB_HOME), pw_explorer_sprites[!!dark][PW_XS_CRUMB_HOME].height);
    else if (info->pidl)
    {
        /* The chain below the desktop: each level's own name, a chevron between. */
        ITEMIDLIST *chain[32]; int depth = 0, i;
        ITEMIDLIST *walk = ILClone(info->pidl);
        while (walk && walk->mkid.cb && depth < 32) { chain[depth++] = ILClone(walk); ILRemoveLastID(walk); }
        ILFree(walk);
        for (i = depth - 1; i >= 0; --i)
        {
            WCHAR name[MAX_PATH]; SHFILEINFOW file; RECT r; SIZE size; HGDIOBJ prior;
            if (SHGetFileInfoW((const WCHAR *)chain[i], 0, &file, sizeof(file), SHGFI_PIDL | SHGFI_DISPLAYNAME)) lstrcpynW(name, file.szDisplayName, MAX_PATH);
            else name[0] = 0;
            prior = SelectObject(dc, info->mihawk_style.font);
            GetTextExtentPoint32W(dc, name, lstrlenW(name), &size); SelectObject(dc, prior);
            SetRect(&r, x + 6, 60, x + 6 + size.cx + 1, 84);
            pw_explorer_text_at(dc, info->mihawk_style.font, name, &r, pw_explorer_text(dark, FALSE), DT_LEFT | DT_VCENTER);
            x += 6 + size.cx + 6;
            if (i) { pw_explorer_sprite_part(ui, dc, dark, PW_XS_CRUMB_CHEV, 0, 0, chevron->width, chevron->height, x, 60, chevron->width, chevron->height); x += 18; }
            ILFree(chain[i]);
        }
    }
    RestoreDC(dc, saved);
}

static void pw_explorer_paint(explorer_info *info, HDC dc, const RECT *dirty)
{
    struct pw_explorer *ui = info->ui; const PwExplorerPlace *p = &ui->place;
    BOOL dark = info->mihawk_style.dark;
    RECT bar = {0, 0, ui->width, PW_EXPLORER_TITLE_H}, header = {0, PW_EXPLORER_TITLE_H, ui->width, PW_EXPLORER_HEADER_H - 1};
    RECT divider = {0, PW_EXPLORER_HEADER_H - 1, ui->width, PW_EXPLORER_HEADER_H};
    RECT status = {0, ui->height - PW_EXPLORER_STATUS_H, ui->width, ui->height}, r;
    RECT body = {PW_EXPLORER_NAV_W, PW_EXPLORER_HEADER_H, ui->width, ui->height - PW_EXPLORER_STATUS_H};
    HDC buffer; HPAINTBUFFER glass;
    int i, filter = pw_explorer_filter(ui);
    /* The items area's padding round the shell view (12 px left, 8 px right, 12 px below). */
    if (IntersectRect(&r, &body, dirty)) pw_shell_fill(dc, &body, pw_explorer_body(dark));
    /* The title bar is glass: what is not drawn here shows the Mica Alt backdrop. */
    if (IntersectRect(&r, &bar, dirty) && (glass = pw_shell_glass_begin(dc, &bar, &buffer)))
    {
        pw_explorer_paint_title(info, buffer);
        pw_shell_glass_fix(glass);
        EndBufferedPaint(glass, TRUE);
    }
    if (IntersectRect(&r, &header, dirty) || IntersectRect(&r, &divider, dirty))
    {
        pw_shell_fill(dc, &header, pw_explorer_header(dark));
        pw_shell_fill(dc, &divider, dark ? RGB(61, 61, 61) : RGB(234, 234, 234));
        for (i = 0; i < PW_EXPLORER_NAVIGATION; ++i)
        {
            int element = PX_BACK + i;
            if (ui->hot == element && ui->enabled[element])
                pw_explorer_sprite(ui, dc, dark, ui->pressed == element ? PW_XS_ICONBTN_PRESS : PW_XS_ICONBTN_HOVER, p->navigation[i], 0, 0);
            pw_explorer_sprite(ui, dc, dark, pw_explorer_navigation_sprites[i][!ui->enabled[element]], p->navigation[i], 0, 0);
        }
        pw_explorer_sprite_box(ui, dc, dark, ui->hot == PX_ADDRESS ? PW_XS_ADDRESS_HOVER : PW_XS_ADDRESS, p->address);
        if (!ui->edit || !IsWindowVisible(ui->edit)) pw_explorer_paint_crumbs(info, dc);
        pw_explorer_sprite(ui, dc, dark, ui->hot == PX_SEARCH ? PW_XS_SEARCH_HOVER : PW_XS_SEARCH, p->search, 0, 0);
        if (ui->home) pw_explorer_sprite_moved(ui, dc, dark, PW_XS_SEARCH_TEXT_HOME, (int)p->search.x - pw_explorer_sprites[0][PW_XS_SEARCH].x, 0);
        else
        {
            WCHAR text[MAX_PATH + 8];
            RECT r = {(int)p->search.x + 11, (int)p->search.y + 1, (int)(p->search.x + p->search.w) - 33, (int)(p->search.y + p->search.h) - 1};
            wsprintfW(text, L"Search %s", ui->name);
            pw_explorer_text_at(dc, info->mihawk_style.font, text, &r, pw_explorer_text(dark, TRUE), DT_LEFT | DT_VCENTER | DT_END_ELLIPSIS);
        }
        pw_explorer_sprite_moved(ui, dc, dark, PW_XS_SEARCH_GLYPH, (int)p->search.x - pw_explorer_sprites[0][PW_XS_SEARCH].x, 0);
        pw_explorer_sprite(ui, dc, dark, PW_XS_SEP_1, p->separator[0], 0, 0);
        pw_explorer_sprite(ui, dc, dark, PW_XS_SEP_2, p->separator[1], 0, 0);
        pw_explorer_sprite(ui, dc, dark, filter ? PW_XS_SEP_3_FOLDER : PW_XS_SEP_3, p->separator[2], 0, 0);
        for (i = 0; i < PW_EXPLORER_COMMANDS; ++i)
        {
            int element = PX_COMMAND + i; short s[4];
            BOOL enabled;
            memcpy(s, pw_explorer_command_sprites[i], sizeof(s));
            if (i == PW_EXPLORER_CMD_FILTER && !filter) continue;
            /* See more sits at another fraction after Filter; View's glyph is the view's. */
            if (i == PW_EXPLORER_CMD_MORE && filter) { s[0] = PW_XS_CMD_MORE_FOLDER; s[2] = PW_XS_CMD_MORE_FOLDER_HOVER; s[3] = PW_XS_CMD_MORE_FOLDER_PRESS; }
            if (i == PW_EXPLORER_CMD_VIEW && !ui->home)
                s[0] = ui->view == FVM_ICON ? PW_XS_CMD_VIEW_LARGE : ui->view == FVM_SMALLICON ? PW_XS_CMD_VIEW_SMALL :
                       ui->view == FVM_LIST ? PW_XS_CMD_VIEW_LIST : PW_XS_CMD_VIEW_DETAILS;
            enabled = ui->enabled[element] || s[1] < 0;
            /* Filter on and the details pane open are checked: their own plate (the pointer leaves it as it is). */
            if ((i == PW_EXPLORER_CMD_FILTER && ui->filter) || (i == PW_EXPLORER_CMD_DETAILS && ui->details))
            {
                pw_explorer_sprite(ui, dc, dark, i == PW_EXPLORER_CMD_FILTER ? PW_XS_CMD_FILTER_CHECKED : PW_XS_CMD_DETAILS_CHECKED, p->command[i], 0, 0);
                continue;
            }
            if (ui->hot == element && enabled) pw_explorer_sprite(ui, dc, dark, ui->pressed == element ? s[3] : s[2], p->command[i], 0, 0);
            pw_explorer_sprite(ui, dc, dark, enabled ? s[0] : s[1], p->command[i], 0, 0);
        }
    }
    if (IntersectRect(&r, &status, dirty))
    {
        WCHAR text[64]; SIZE size; HGDIOBJ prior; RECT line;
        pw_shell_fill(dc, &status, pw_explorer_body(dark));
        wsprintfW(text, L"%d item%s", ui->items, ui->items == 1 ? L"" : L"s");
        SetRect(&r, 12, ui->height - 21, 12 + 400, ui->height - 5);
        pw_explorer_text_at(dc, info->mihawk_style.font, text, &r, pw_explorer_text(dark, FALSE), DT_LEFT | DT_VCENTER);
        prior = SelectObject(dc, info->mihawk_style.font); GetTextExtentPoint32W(dc, text, lstrlenW(text), &size); SelectObject(dc, prior);
        SetRect(&line, 12 + size.cx + 10, ui->height - 20, 12 + size.cx + 11, ui->height - 6);
        pw_shell_fill(dc, &line, dark ? RGB(47, 47, 47) : RGB(240, 240, 240));
        if (ui->selected)
        {
            int x = line.right + 10;
            wsprintfW(text, L"%d item%s selected", ui->selected, ui->selected == 1 ? L"" : L"s");
            SetRect(&r, x, ui->height - 21, x + 400, ui->height - 5);
            pw_explorer_text_at(dc, info->mihawk_style.font, text, &r, pw_explorer_text(dark, FALSE), DT_LEFT | DT_VCENTER);
        }
        /* The view buttons: checked for details and large icons, disabled on Home. */
        pw_explorer_sprite(ui, dc, dark, !ui->enabled[PX_STATUS_DETAILS] ? PW_XS_STATUS_DETAILS_DISABLED :
                           ui->view == FVM_DETAILS ? PW_XS_STATUS_DETAILS : PW_XS_STATUS_DETAILS_PLAIN, p->status_details, 0, 0);
        pw_explorer_sprite(ui, dc, dark, !ui->enabled[PX_STATUS_LARGE] ? PW_XS_STATUS_LARGE_DISABLED :
                           ui->view == FVM_ICON ? PW_XS_STATUS_LARGE_CHECKED : PW_XS_STATUS_LARGE, p->status_large, 0, 0);
    }
}

