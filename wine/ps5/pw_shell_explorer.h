static void pw_explorer_refresh(explorer_info *info);
static void pw_explorer_style_view(explorer_info *info);
static explorer_info *pw_explorer_info(HWND child) { return (explorer_info *)GetWindowLongPtrW(GetParent(child), EXPLORER_INFO_INDEX); }

static void pw_explorer_title(explorer_info *info)
{
    WCHAR title[MAX_PATH + 32];
    wsprintfW(title, L"%s - File Explorer", info->ui->name);
    SetWindowTextW(info->main_window, title);
}
/* Home replaces the shell view; the browser keeps its location and history behind it. */
static void pw_explorer_show_home(explorer_info *info, BOOL ahead)
{
    struct pw_explorer *ui = info->ui;
    ui->home = TRUE; ui->home_ahead = ahead; ui->location = PW_LOC_HOME; ui->page_selected = -1;
    lstrcpyW(ui->name, L"Home");
    pw_explorer_layout(info, ui->width, ui->height);
    pw_explorer_title(info);
    pw_explorer_selection(info);
    InvalidateRect(info->main_window, NULL, FALSE);
    if (ui->nav) InvalidateRect(ui->nav, NULL, FALSE);
    if (ui->page) InvalidateRect(ui->page, NULL, FALSE);
}
static void pw_explorer_browse(explorer_info *info, ITEMIDLIST *pidl)
{
    struct pw_explorer *ui = info->ui;
    if (!pidl) return;
    if (ui->home && !info->pidl) ui->from_home = TRUE;
    ui->home = FALSE; ui->home_ahead = FALSE;
    if (info->pidl && ILIsEqual(info->pidl, pidl)) { pw_explorer_location(info); return; }
    IExplorerBrowser_BrowseToIDList(info->browser, pidl, SBSP_ABSOLUTE);
}
static void pw_explorer_go(explorer_info *info, int location)
{
    ITEMIDLIST *pidl;
    if (location == PW_LOC_HOME) { pw_explorer_show_home(info, FALSE); return; }
    if ((pidl = pw_explorer_pidl(location))) { pw_explorer_browse(info, pidl); CoTaskMemFree(pidl); }
}
/* A navigation's new view is shown and painted inside the navigation (shell32's CreateViewWindow updates it), before the
 * browser reports it: the browser's window does not draw from the navigation's start (patch 1152's OnNavigationPending)
 * until the view is styled, so the old folder stays on screen until the new one is drawn as the prototype's. */
static void pw_explorer_freeze(explorer_info *info, BOOL freeze)
{
    struct pw_explorer *ui = info->ui; IShellBrowser *shell; HWND hwnd = NULL;
    if (!ui) return;
    if (!freeze)
    {
        if (!(hwnd = ui->frozen)) return;
        ui->frozen = NULL;
        SendMessageW(hwnd, WM_SETREDRAW, TRUE, 0);
        RedrawWindow(hwnd, NULL, NULL, RDW_INVALIDATE | RDW_ERASE | RDW_FRAME | RDW_ALLCHILDREN);
        return;
    }
    if (ui->frozen || FAILED(IExplorerBrowser_QueryInterface(info->browser, &IID_IShellBrowser, (void **)&shell))) return;
    if (SUCCEEDED(IShellBrowser_GetWindow(shell, &hwnd)) && hwnd && IsWindowVisible(hwnd))
    {
        SendMessageW(hwnd, WM_SETREDRAW, FALSE, 0);
        ui->frozen = hwnd;
    }
    IShellBrowser_Release(shell);
}
static void pw_explorer_navigation_pending(explorer_info *info) { pw_explorer_freeze(info, TRUE); }
static void pw_explorer_navigation_failed(explorer_info *info) { pw_explorer_freeze(info, FALSE); }
/* What desktop-session checks: a view created while its window was held cannot have painted before it was styled. */
static void pw_explorer_view_created(explorer_info *info, IShellView *view)
{
    HWND hwnd = NULL; char line[96];
    if (!info->ui || !view || FAILED(IShellView_GetWindow(view, &hwnd))) return;
    wsprintfA(line, "pw-explorer: view created held=%d visible=%d\n", info->ui->frozen != NULL, IsWindowVisible(hwnd));
    OutputDebugStringA(line);
}
/* Called when the browser completed a navigation (OnNavigationComplete) and when Home gives way to the browser. */
static void pw_explorer_location(explorer_info *info)
{
    struct pw_explorer *ui = info->ui;
    SHFILEINFOW file;
    if (!ui) return;
    ui->home = FALSE;
    ui->location = pw_explorer_location_of(info->pidl);
    if (info->pidl && SHGetFileInfoW((const WCHAR *)info->pidl, 0, &file, sizeof(file), SHGFI_PIDL | SHGFI_DISPLAYNAME))
        lstrcpynW(ui->name, file.szDisplayName, MAX_PATH);
    ui->sort_column = PW_COLUMN_NAME; ui->descending = FALSE; ui->list_hot = -1; /* a new view sorts by name */
    if (ui->filter_pidl && !(info->pidl && ILIsEqual(info->pidl, ui->filter_pidl)))
    { ILFree(ui->filter_pidl); ui->filter_pidl = NULL; ui->filter = PW_FILTER_NONE; }
    ui->pane_count = -1;
    pw_explorer_layout(info, ui->width, ui->height);
    pw_explorer_style_view(info);
    pw_explorer_freeze(info, FALSE);
    pw_explorer_refresh(info);
    /* The title last: whoever sees the new location's name (another process reads it at once) finds its view styled
     * and shown, not still held (the gate's shell32 case read the title, then found no visible list). */
    pw_explorer_title(info);
    /* The browser publishes its travel state after this callback. */
    PostMessageW(info->main_window, WM_TIMER, PW_EXPLORER_TIMER, 0);
}
static void pw_explorer_navigate(explorer_info *info, int element)
{
    struct pw_explorer *ui = info->ui;
    if (element == PX_REFRESH)
    {
        IShellView *view;
        if (ui->home) { InvalidateRect(ui->page, NULL, FALSE); return; }
        if ((view = pw_explorer_view(info))) { IShellView_Refresh(view); IShellView_Release(view); }
        return;
    }
    if (ui->home)
    {
        /* Forward from Home returns to the location Back left. */
        if (element == PX_FORWARD && ui->home_ahead) { ui->home = FALSE; pw_explorer_location(info); }
        return;
    }
    if (element == PX_BACK && !(ui->navigation_state & 2)) { if (ui->from_home) pw_explorer_show_home(info, TRUE); return; }
    IExplorerBrowser_BrowseToObject(info->browser, NULL, element == PX_BACK ? SBSP_NAVIGATEBACK :
                                    element == PX_FORWARD ? SBSP_NAVIGATEFORWARD : SBSP_PARENT);
}

/* ---------- Filter and the selection: the browsers' site ---------- */
/* The prototype's FILTERS (PW_FILTER_*): a kind of item, by its attributes and its name's extension. */
static const WCHAR *const pw_explorer_filter_names[PW_FILTERS] = {NULL, L"Folders", L"Documents", L"Pictures", L"Music",
                                                                  L"Videos", L"Applications"};
static BOOL pw_explorer_filter_test(int filter, IShellFolder *folder, const ITEMIDLIST *child)
{
    static const WCHAR *const specs[PW_FILTERS] = {NULL, NULL, L"*.txt;*.pdf;*.xlsx;*.docx;*.md;*.rtf",
        L"*.png;*.jpg;*.jpeg;*.gif;*.bmp;*.webp", L"*.mp3;*.flac;*.wav;*.m4a", L"*.mp4;*.mkv;*.avi;*.mov", L"*.exe;*.lnk"};
    SFGAOF attributes = SFGAO_FOLDER | SFGAO_STREAM | SFGAO_LINK; STRRET name; WCHAR text[MAX_PATH] = L"";
    if (FAILED(IShellFolder_GetAttributesOf(folder, 1, &child, &attributes))) attributes = 0;
    if (filter == PW_FILTER_FOLDERS) return (attributes & SFGAO_FOLDER) && !(attributes & SFGAO_STREAM);
    if (filter == PW_FILTER_APPS && (attributes & SFGAO_LINK)) return TRUE;
    if (SUCCEEDED(IShellFolder_GetDisplayNameOf(folder, child, SHGDN_INFOLDER | SHGDN_FORPARSING, &name)))
        StrRetToBufW(&name, child, text, MAX_PATH);
    return !(attributes & SFGAO_FOLDER) && PathMatchSpecW(text, specs[filter]);
}
/* The folder a shell view shows, as its folder knows itself (absolute pidl; ILFree it). */
static ITEMIDLIST *pw_explorer_view_folder(IShellView *view)
{
    IFolderView *folder_view; IPersistFolder2 *persist; ITEMIDLIST *pidl = NULL;
    if (!view || FAILED(IShellView_QueryInterface(view, &IID_IFolderView, (void **)&folder_view))) return NULL;
    if (SUCCEEDED(IFolderView_GetFolder(folder_view, &IID_IPersistFolder2, (void **)&persist)))
    {
        IPersistFolder2_GetCurFolder(persist, &pidl);
        IPersistFolder2_Release(persist);
    }
    IFolderView_Release(folder_view);
    return pidl;
}
