"""The dialogs' fixed pixels as the approved prototype draws them: its 32 px message box icons and its four footer
button looks, for Wine's message box (dlls/user32/msgbox.c, patch 2490).

themes/windows11/dialogs/*-light.json are the prototype's elements captured alone over black and over white
(tools/measure-prototype-sprites.mjs, from prototypes/windows11-shell at 1920 x 1080):

  msgbox-light.json:  ... msgbox light 'icon-warning=.dlg-msg-icon' 'btn-default=.dlg-msg-foot .dlg-btn:nth-child(1)'
                            'btn-normal=.dlg-msg-foot .dlg-btn:nth-child(2)' 'btn-normal-hover=...~hover'
                            'btn-normal-press=...~press' 'btn-default-hover=...~hover' 'btn-default-press=...~press'
  msgbox-error-light.json: ... msgbox-error light 'icon-error=.dlg-msg-icon'
  msgbox-info-light.json:  ... msgbox-info light 'icon-info=.dlg-msg-icon'
  taskdialog-light.json:   ... taskdialog light 'icon-task=.icon.dlg-task-icon'

The prototype's classic dialogs keep the light palette in the dark theme (css/dialogs.css `.dlg[data-theme=light]`), so
one set serves both. Over black a pixel is its premultiplied colour, white minus black is 255 minus its alpha.

Writes .deps/windows11-theme/pw_dialog_sprites.h (the indices msgbox.c names)."""
import base64
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'themes' / 'windows11' / 'dialogs'
OUTPUT = ROOT / '.deps' / 'windows11-theme' / 'pw_dialog_sprites.h'
# (capture file, its element, the header's name)
SPRITES = [
    ('msgbox-light', 'icon-warning', 'PW_DIALOG_ICON_WARNING'),
    ('msgbox-error-light', 'icon-error', 'PW_DIALOG_ICON_ERROR'),
    ('msgbox-info-light', 'icon-info', 'PW_DIALOG_ICON_INFO'),
    ('taskdialog-light', 'icon-task', 'PW_DIALOG_ICON_QUESTION'),
    ('msgbox-light', 'btn-normal', 'PW_DIALOG_BUTTON_NORMAL'),
    ('msgbox-light', 'btn-default', 'PW_DIALOG_BUTTON_DEFAULT'),
    ('msgbox-light', 'btn-normal-hover', 'PW_DIALOG_BUTTON_NORMAL_HOVER'),
    ('msgbox-light', 'btn-normal-press', 'PW_DIALOG_BUTTON_NORMAL_PRESS'),
    ('msgbox-light', 'btn-default-hover', 'PW_DIALOG_BUTTON_DEFAULT_HOVER'),
    ('msgbox-light', 'btn-default-press', 'PW_DIALOG_BUTTON_DEFAULT_PRESS'),
]


def premultiplied(sprite):
    """BGRA words, premultiplied, row by row; alpha is the mean of the channels' (they agree to a level)."""
    black, white = base64.b64decode(sprite['black']), base64.b64decode(sprite['white'])
    words = []
    for i in range(sprite['w'] * sprite['h']):
        alphas = [255 - (white[i * 3 + k] - black[i * 3 + k]) for k in range(3)]
        if max(alphas) - min(alphas) > 2:
            raise ValueError(f'pixel {i}: per-channel alpha {alphas} (subpixel text?) cannot be one AlphaBlend alpha')
        alpha = max(0, min(255, round(sum(alphas) / 3)))
        red, green, blue = (min(alpha, black[i * 3 + k]) for k in range(3))
        words.append(alpha << 24 | red << 16 | green << 8 | blue)
    return words


def main():
    captures = {}
    sprites = []
    for part, name, header in SPRITES:
        if part not in captures:
            captures[part] = json.loads((SOURCE / f'{part}.json').read_text())['sprites']
        found = captures[part].get(name)
        if not found:
            raise ValueError(f'{part}: no measured sprite {name}')
        sprites.append((header, found))
    lines = ['/* Generated by tools/build-dialog-sprites.py from themes/windows11/dialogs: do not edit. */',
             '#ifndef PW_DIALOG_SPRITES_H', '#define PW_DIALOG_SPRITES_H',
             'enum { ' + ', '.join(header for header, _ in sprites) + ', PW_DIALOG_SPRITE_COUNT };',
             'struct pw_dialog_sprite { int width, height; const unsigned int *bgra; };']
    for header, found in sprites:
        words = premultiplied(found)
        body = ',\n'.join(','.join(f'0x{word:08x}' for word in words[i:i + 12]) for i in range(0, len(words), 12))
        lines.append(f'static const unsigned int pw_dialog_{header.lower()[10:]}_bgra[] = {{\n{body}}};')
    lines.append('static const struct pw_dialog_sprite pw_dialog_sprites[PW_DIALOG_SPRITE_COUNT] = {')
    lines.append('    ' + ', '.join(f'{{{found["w"]}, {found["h"]}, pw_dialog_{header.lower()[10:]}_bgra}}'
                                    for header, found in sprites))
    lines += ['};', '#endif', '']
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    text = '\n'.join(lines)
    if not OUTPUT.exists() or OUTPUT.read_text() != text:
        OUTPUT.write_text(text)
    print(json.dumps({'sprites': len(sprites), 'header': str(OUTPUT.relative_to(ROOT))}))


if __name__ == '__main__':
    main()
