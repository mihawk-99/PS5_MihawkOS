"""The Settings app's fixed pixels as the approved prototype draws them (src/pw_settings.c): the navigation's tinted icons,
the avatar, the search box, the title bar's back button, app icon and caption buttons, the device picture's frame, the
hero tiles' icons, the cards' icons, chevrons, the combo box's chevron, the toggle, the slider and Personalization's preview
taskbar, light and dark.

themes/windows11/settings/<page>-<theme>.json are the prototype's elements captured alone over black and over white
(tools/measure-prototype-sprites.mjs, prototypes/windows11-shell at 1920 x 1080, ?open=settings&settingsPage=<page>):

  home:            avatar=.stg-avatar search=.stg-search-input nav-1..12=.stg-nav-item:nth-child(N of .stg-nav-item)
                   .stg-nav-icon back=.stg-tb-btn app-icon=.stg-tb-icon caption-min/max/close=.window.active
                   .window-caption-btn:nth-child(N of .window-caption-btn) device-frame=.stg-device-pic!.stg-device-screen
                   hero-wifi/hero-update=.stg-hero-tile:nth-child(N of .stg-hero-tile) .stg-hero-tile-icon
                   chevron-row=.stg-home-row .icon combo-chevron=.combo-chevron
  personalization: card-icon-p1..3=.stg-card:nth-child(N of .stg-card) .stg-card-icon chevron-card=.stg-card-chev
                   preview-taskbar=.stg-preview-taskbar
  display:         icon-brightness/night/hdr/scale/resolution (the cards' .stg-card-icon) expand=.stg-exp-chev
                   toggle-off=.toggle-track slider=input.slider

Over black a pixel is its premultiplied colour; white minus black is 255 minus its alpha. Writes
.deps/windows11-theme/pw_settings_sprites.h: PW_SETTINGS_<NAME> and pw_settings_sprites[dark][name]."""
import base64
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'themes' / 'windows11' / 'settings'
OUTPUT = ROOT / '.deps' / 'windows11-theme' / 'pw_settings_sprites.h'
PAGES = ('home', 'personalization', 'display')


def premultiplied(sprite):
    """BGRA words, premultiplied, row by row; alpha is the mean of the channels' (text is grey, they agree)."""
    black, white = base64.b64decode(sprite['black']), base64.b64decode(sprite['white'])
    words = []
    for i in range(sprite['w'] * sprite['h']):
        alphas = [255 - (white[i * 3 + k] - black[i * 3 + k]) for k in range(3)]
        alpha = max(0, min(255, round(sum(alphas) / 3)))
        red, green, blue = (min(alpha, black[i * 3 + k]) for k in range(3))
        words.append(alpha << 24 | red << 16 | green << 8 | blue)
    return words


def main():
    themes = {}
    for theme in ('light', 'dark'):
        found = {}
        for page in PAGES:
            found.update(json.loads((SOURCE / f'{page}-{theme}.json').read_text())['sprites'])
        themes[theme] = found
    names = list(themes['light'])
    if set(names) != set(themes['dark']):
        raise ValueError('light and dark captures name different sprites')
    enum = [f'PW_SETTINGS_{n.upper().replace("-", "_")}' for n in names]
    lines = ['/* Generated by tools/build-settings-sprites.py from themes/windows11/settings: do not edit. */',
             '#ifndef PW_SETTINGS_SPRITES_H', '#define PW_SETTINGS_SPRITES_H',
             'enum { ' + ', '.join(enum) + ', PW_SETTINGS_SPRITE_COUNT };',
             'struct pw_settings_sprite { int width, height; const unsigned int *bgra; };']
    for theme, found in themes.items():
        for n in names:
            words = premultiplied(found[n])
            body = ',\n'.join(','.join(f'0x{w:08x}' for w in words[i:i + 12]) for i in range(0, len(words), 12))
            lines.append(f'static const unsigned int pw_settings_{theme}_{n.replace("-", "_")}[] = {{\n{body}}};')
    lines.append('static const struct pw_settings_sprite pw_settings_sprites[2][PW_SETTINGS_SPRITE_COUNT] = {')
    for theme, found in themes.items():
        lines.append('    {' + ', '.join(f'{{{found[n]["w"]}, {found[n]["h"]}, pw_settings_{theme}_{n.replace("-", "_")}}}'
                                         for n in names) + '},')
    lines += ['};', '#endif', '']
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    text = '\n'.join(lines)
    if not OUTPUT.exists() or OUTPUT.read_text() != text:
        OUTPUT.write_text(text)
    print(json.dumps({'sprites': len(names), 'header': str(OUTPUT.relative_to(ROOT))}))


if __name__ == '__main__':
    main()
